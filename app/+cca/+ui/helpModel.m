function items = lawPictures(D)
% the law pictures' words (app/assets/model/law_pictures.json, worker P's schema cca-model-laws/1: laws[].code and
% words_controller): one row a law, its name with its reference number read from the data at run time (the list of
% runs, else the laws' table), and the words under its controller; none where the file is absent
items = cell(0, 2);
f = fullfile(D.root, 'assets', 'model', 'law_pictures.json');
if ~isfile(f)
    return
end
try
    J = jsondecode(fileread(f));
catch
    return
end
if ~isstruct(J) || ~isfield(J, 'laws')
    return
end
L = J.laws;
if iscell(L)
    L = [L{:}];
end
for k = 1:numel(L)
    if ~isfield(L(k), 'code') || ~isfield(L(k), 'words_controller')
        continue
    end
    t = lawName(D, char(L(k).code));
    c = char(L(k).words_controller);
    if ~isempty(t) && ~isempty(c)
        items(end + 1, :) = {t, c}; %#ok<AGROW>
    end
end
end

function t = lawName(D, code)
% a law's name with its reference number as the paper prints it: the list of runs (D.runinfo.laws), else the laws'
% table (D.laws, D.others)
t = '';
W = D.runinfo.laws;
if iscell(W), W = [W{:}]; end
m = W(strcmp({W.code}, code));
if ~isempty(m)
    t = m(1).law;
    return
end
for X = {asArray(D.laws), asArray(D.others)}
    m = X{1}(strcmp({X{1}.code}, code));
    if ~isempty(m)
        t = m(1).name;
        return
    end
end
end

function X = asArray(X)
if iscell(X), X = [X{:}]; end
X = reshape(X, 1, []);
end
