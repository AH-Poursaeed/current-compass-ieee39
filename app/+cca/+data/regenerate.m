function [R, info] = regenerate(D, varargin)
%REGENERATE  Run the data step (app/tools/make_app_data.py, its release mode) into a temporary folder: it reads
%   only app/data (the released record, the inputs file, the paper's texts) and regenerates every number file; each
%   is compared with app/data/MANIFEST.json, byte for byte (sha256). The files shipped as data (the released record,
%   the inputs file, the paper's texts) are named in info.shipped.
%   [R, info] = cca.data.regenerate(D)                       R(i): file, from, want, got, equal
%   [R, info] = cca.data.regenerate(D, Python="C:\...\python.exe", Keep=true)
%   info.started is false when no Python could be started here (info.output says why); info.status is the data
%   step's exit status.
% (the options are read by hand: the function holds nested functions)
opts = struct('Python', "", 'Keep', false);
for k = 1:2:numel(varargin)
    switch lower(string(varargin{k}))
        case "python"
            opts.Python = string(varargin{k + 1});
        case "keep"
            opts.Keep = logical(varargin{k + 1});
        otherwise
            error('cca:data:regenerate', 'Unknown option: %s', string(varargin{k}));
    end
end
script = fullfile(D.root, 'tools', 'make_app_data.py');
tmp = tempname;
mkdir(tmp);
py = opts.Python;
if py == ""
    py = pythonExe();
end
% the program and its arguments are passed as a list, with no shell between (no quoting rule of any shell applies);
% -I: the interpreter isolated from the user's site folder and environment, so only the released files are read
args = {char(py), '-I', script, '--into', tmp};
[st, out] = runList(args, D.repo);
info = struct('status', st, 'started', st ~= -1, 'output', regexprep(out, '\s+$', ''), 'folder', tmp, 'command', ...
    strjoin(args, ' '), 'equal', 0, 'of', 0, 'shipped', {{}});
R = struct('file', {}, 'from', {}, 'want', {}, 'got', {}, 'equal', {});
rf = fullfile(tmp, 'data', 'REGEN.json');
if st ~= 0 || ~isfile(rf)
    finish();
    return
end
M = D.manifest.files;
if iscell(M), M = [M{:}]; end
N = jsondecode(fileread(rf));
G = N.files;
if iscell(G), G = [G{:}]; end
for i = 1:numel(G)                       % every number file the release mode regenerated
    w = M(strcmp({M.file}, G(i).file));
    want = '';
    from = 'regenerated by this run (not in MANIFEST.json)';
    if ~isempty(w)
        want = w(1).sha256;
        from = fromOf(w(1));
    end
    add(G(i).file, from, want, fullfile(tmp, 'data', G(i).file));
end
info.shipped = cellstr(string(N.shipped));
info.equal = sum([R.equal]);
info.of = numel(R);
finish();

    function add(file, from, want, p)
        got = '';
        if isfile(p)
            got = sha256file(p);
        end
        R(end + 1) = struct('file', file, 'from', from, 'want', want, 'got', got, ...
            'equal', ~isempty(want) && strcmp(got, want));
    end

    function finish()
        if ~opts.Keep && isfolder(tmp)
            rmdir(tmp, 's');
        end
    end
end

function s = fromOf(m)
s = '';
if isfield(m, 'from')
    s = m.from;
end
end

function py = pythonExe()
% the Python that MATLAB is set to use (pyenv), else the one on the system path
py = "python";
if ~ispc
    py = "python3";
end
try
    pe = pyenv;
    if strlength(pe.Executable) > 0 && isfile(pe.Executable)
        py = pe.Executable;
    end
catch
end
end

function [st, out] = runList(args, folder)
% run a program with its arguments given as a list (java.lang.ProcessBuilder: no shell), in the folder given; its
% output and errors together. st is the exit status, or -1 when the program could not be started (out says why)
try
    lst = java.util.ArrayList();
    for k = 1:numel(args)
        lst.add(java.lang.String(args{k}));
    end
    pb = java.lang.ProcessBuilder(lst);
    pb.directory(java.io.File(folder));
    pb.redirectErrorStream(true);
    p = pb.start();
catch err
    st = -1;
    out = sprintf('The program %s could not be started: %s', args{1}, err.message);
    return
end
rd = java.io.BufferedReader(java.io.InputStreamReader(p.getInputStream()));
lines = {};
ln = rd.readLine();
while ~(isnumeric(ln) && isempty(ln))   % a Java null (the end of the output) arrives as []; a line as a string
    lines{end + 1} = char(ln); %#ok<AGROW>
    ln = rd.readLine();
end
rd.close();
st = p.waitFor();
out = strjoin(lines, newline);
end

function h = sha256file(p)
fid = fopen(p, 'r');
b = fread(fid, Inf, '*uint8');
fclose(fid);
md = java.security.MessageDigest.getInstance('SHA-256');
md.update(b);
d = typecast(md.digest(), 'uint8');
h = lower(reshape(dec2hex(d, 2).', 1, []));
end
